#!/usr/bin/env python3
"""
This script will take all the metadata files generated by the pipeline and combine them.
"""

import argparse
import sys
import pandas as pd

def name_getter(reference_file):
    # This function will great a dictionary of sequence headers using their accesion numbers as the key. 
    with open(reference_file, 'r') as f:
        lines = f.readlines()
    name_dict = {}
    for line in lines:
        if line.startswith('>'):
            accession = line.split()[0][1:]
            header = line.strip().split(accession)[1]
            try:
                header = header.lstrip(' |').split(',')[0]
            except:
                header = header.lstrip(' |')

                
            name_dict[accession] = header
    return name_dict

def consensus_handler(consensus_seqs):
    consensus_refs = []
    for i in consensus_seqs.lstrip("[").rstrip("]").split(", "):
        file_name = i.split("/")[-1]
        consensus_refs.append(file_name.lstrip('barcode0123456789').lstrip('_').split(".fasta")[0])

        with open(i,"r") as file:
            for line in file:
                if line.startswith(">"):
                    print(line)


    print(consensus_refs)

    return consensus_refs


def read_files(read_counts,name_dict,consensus_refs):
    for i in read_counts.lstrip("[").rstrip("]").split(", "):
        file_name = i.split("/")[-1]
        sample_ID = i.split("/")[-1].split("_")[0]

        if file_name == f"{sample_ID}_read_counts.tsv":
            read_mapper_counts_df = pd.read_csv(i, sep="\t", header=0)
            read_mapper_counts_df['Sample_ID'] = sample_ID

        if f"{sample_ID}_ref_" in file_name:
            ref_counts_df = pd.read_csv(i, sep="\t", header=0)
            ref_counts_df['Sample_ID'] = sample_ID
            ref_counts_df['reference'] = ref_counts_df['reference'].str.split("_ref_").str[-1]
            ref_counts_df = ref_counts_df.rename(columns={'reads_mapped': 'reads_mapped_repeat'})
            try:
                all_ref_counts_df = pd.concat([all_ref_counts_df, ref_counts_df], ignore_index=True)
            except NameError:
                all_ref_counts_df = ref_counts_df.copy()
        
        if file_name == f"{sample_ID}_top_map_read_counts.tsv":
            all_ref_counts_df = pd.read_csv(i, sep="\t", header=0)
            all_ref_counts_df['Sample_ID'] = sample_ID
            all_ref_counts_df = all_ref_counts_df.rename(columns={'reads_mapped': 'reads_mapped_repeat'})
        
        if file_name == f"{sample_ID}_filtered_read_counts.csv":
            filtered_read_counts_df = pd.read_csv(i, sep=",", names=['Sample_ID', 'filtered_read_count', 'treatement'])

        if file_name == f"{sample_ID}_unfiltered_read_counts.csv":
            unfiltered_read_counts_df = pd.read_csv(i, sep=",", names=['Sample_ID', 'unfiltered_read_count', 'treatement'])


    try:
        combined_df = pd.merge(read_mapper_counts_df, all_ref_counts_df, on='reference', how='outer', suffixes=(None, '_y'))
        col_order = ['Sample_ID', 'unfiltered_read_count', 'filtered_read_count', 'reference', 'reads_mapped', 'reads_mapped_repeat']
        
    except:
        combined_df = read_mapper_counts_df.copy()
        col_order = ['Sample_ID', 'unfiltered_read_count', 'filtered_read_count', 'reference', 'reads_mapped']

    combined_df = pd.merge(combined_df, filtered_read_counts_df, on='Sample_ID', how='outer', suffixes=(None, '_y'))
    combined_df = pd.merge(combined_df, unfiltered_read_counts_df, on='Sample_ID', how='outer', suffixes=(None, '_y'))
    combined_df = combined_df.drop(columns=[col for col in combined_df.columns if col.endswith('_y')])
    combined_df = combined_df.drop(columns="treatement")
    
    combined_df = combined_df[col_order]

    # Adding in species names and ncbi links from ref headers
    species_names = []
    ncbi_links = []
    consensus_generated = []

    for ref in combined_df.reference:
        species_names.append(name_dict[ref])
        ncbi_links.append(f'https://www.ncbi.nlm.nih.gov/nuccore/{ref}')
        if ref in consensus_refs:
            consensus_generated.append("Yes")
        else:
            consensus_generated.append("No")

    combined_df['species'] = species_names
    combined_df['ncbi_link'] = ncbi_links
    combined_df['consensus_generated'] = consensus_generated

    combined_df = combined_df.fillna(0)
    print(f"\n\n{combined_df}")

    return combined_df
    


if __name__ == '__main__':
    parser = argparse.ArgumentParser(
        description="Combine WaSPPipe metadata files into a single CSV file per sample.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s --reference_file references.fasta --consensus_seqs  "consensus_seq [...]" -r "read_counts.csv [...]"
        """
    )
    
    parser.add_argument(
        "-r", "--read_counts",
        required=True,
        help="Lits of paths to input read counts files"
    )
    parser.add_argument(
            "--reference_file",
            required=True,
            help="Path to input reference file"
        )
    parser.add_argument(
            "--consensus_seqs",
            required=True,
            help="List of paths to generated consensus sequences files"
        )
    
    args = parser.parse_args()
    name_dict = name_getter(args.reference_file)
    consensus_refs = consensus_handler(args.consensus_seqs)
    read_files(args.read_counts, name_dict, consensus_refs)
