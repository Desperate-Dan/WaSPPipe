#!/usr/bin/env python3
"""
This script will take all the metadata files generated by the pipeline and combine them.
"""
import os
import argparse
import sys
import pandas as pd

def metadata_combine_func(metadata_files,run_id):
    df_list = []
    for i in metadata_files.lstrip("[").rstrip("]").split():
        df_list.append(pd.read_csv(i, header=0))

    metadata_df = pd.concat(df_list)

    cwd = os.getcwd()
    metadata_df.to_csv(f'{cwd}/{run_id}_run_metadata.csv', index=False)






if __name__ == '__main__':
    parser = argparse.ArgumentParser(
        description="Combine WaSPPipe metadata files into a single CSV file per run.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s --metadata_files "metadata_files [...]" --run_id RUN_ID
        """
    )
    
    parser.add_argument(
        "--metadata_files",
        required=True,
        help="Lits of input metadata files"
    )
    parser.add_argument(
        "--run_id",
        required=True,
        help="Run ID to append to output file"
    )
    
    args = parser.parse_args()
    metadata_combine_func(args.metadata_files, args.run_id)
    